// Package declarationgen owns TypeScript output-file conventions shared by
// the focused emitters.
package declarationgen

import "google.golang.org/protobuf/compiler/protogen"

// GeneratedFile creates a TypeScript output with the repository's generated
// source banner.
func GeneratedFile(plugin *protogen.Plugin, name, source string) *protogen.GeneratedFile {
	g := plugin.NewGeneratedFile(name, "")
	g.P("// Code generated by protoc-gen-kit-typescript. DO NOT EDIT.")
	g.P("// source: ", source)
	g.P()
	return g
}
