// Package lifecyclegen emits public sandbox-handle lifecycle orchestration from
// the portable lifecycle registry.
package lifecyclegen

import (
	"fmt"
	"strings"

	"github.com/sandbox-kit/kit/tooling/internal/go/naming"
	"github.com/sandbox-kit/kit/tooling/internal/model"
	"github.com/sandbox-kit/kit/tooling/internal/spec"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
)

func Generate(plugin *protogen.Plugin, file *protogen.File, lifecycle spec.Lifecycle, surface model.APIModule) error {
	if file.Desc.Path() != "kit/sandbox/v1/client.proto" {
		return nil
	}
	g := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+".lifecycle.gen.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-kit-go. DO NOT EDIT.")
	g.P("// source: specs/lifecycle.yaml")
	g.P("package ", file.GoPackageName)
	g.P()
	g.P("func staticLifecycleCapabilities(operations any) []LifecycleCapability {")
	g.P("values := make([]LifecycleCapability, 0, ", len(lifecycle.Operations), ")")
	for _, operation := range lifecycle.Operations {
		iface := surface.TypesByID[operation.Interface]
		g.P("if _, ok := operations.(", iface.Name, "); ok { values = append(values, LifecycleCapability", naming.Identifier(operation.Capability), ") }")
	}
	g.P("return values")
	g.P("}")
	for _, operation := range lifecycle.Operations {
		if err := emitOperation(g, plugin, operation, surface); err != nil {
			return err
		}
	}
	return nil
}

func emitOperation(g *protogen.GeneratedFile, plugin *protogen.Plugin, operation spec.LifecycleOperation, surface model.APIModule) error {
	iface := surface.TypesByID[operation.Interface]
	var callable spec.Callable
	found := false
	for _, method := range iface.Methods {
		if method.ID == operation.Method {
			callable, found = method, true
			break
		}
	}
	if !found {
		return fmt.Errorf("lifecycle %s: missing %s.%s", operation.ID, operation.Interface, operation.Method)
	}
	publicName := naming.Identifier(operation.ID)
	optionType := protogen.GoIdent{}
	if operation.Options != "" {
		optionType = findMessage(plugin, protoreflect.FullName("kit.sandbox.v1."+operation.Options))
		if optionType.GoName == "" {
			return fmt.Errorf("lifecycle %s: missing Go option type %s", operation.ID, operation.Options)
		}
	}
	result := "error"
	if operation.Outcome == "exit_result" {
		result = "(*ExitResult, error)"
	}
	g.P("func (s *Sandbox) ", publicName, "(ctx ", protogen.GoIdent{GoName: "Context", GoImportPath: "context"}, func() string {
		if optionType.GoName == "" {
			return ""
		}
		return ", options *" + optionType.GoName
	}(), ") ", result, " {")
	if operation.Timeout {
		g.P("var timeout *", protogen.GoIdent{GoName: "Duration", GoImportPath: "time"})
		g.P("if options != nil { timeout = options.Timeout }")
	} else {
		g.P("var timeout *", protogen.GoIdent{GoName: "Duration", GoImportPath: "time"})
	}
	g.P("operationContext, cancel, err := s.operationContext(ctx, ", fmt.Sprintf("%q", operation.ID), ", timeout)")
	if operation.Outcome == "exit_result" {
		g.P("if err != nil { return nil, err }")
	} else {
		g.P("if err != nil { return err }")
	}
	g.P("defer cancel()")
	g.P("capability, ok := s.operations.(", iface.Name, ")")
	if operation.Outcome == "exit_result" {
		g.P("if !ok { return nil, s.unsupported(", fmt.Sprintf("%q", operation.ID), ") }")
	} else {
		g.P("if !ok { return s.unsupported(", fmt.Sprintf("%q", operation.ID), ") }")
	}
	args := []string{"operationContext", "s.ID()"}
	if optionType.GoName != "" {
		args = append(args, "options")
	}
	methodName := callable.Name
	if operation.Outcome == "exit_result" {
		g.P("outcome, err := capability.", methodName, "(", strings.Join(args, ", "), ")")
		g.P("if err != nil { return outcome, WithErrorContext(err, s.ProviderName(), ", fmt.Sprintf("%q", operation.ID), ") }")
		g.P("s.markTerminal(SandboxState", naming.Identifier(operation.TerminalState), ", ", fmt.Sprintf("%q", operation.TerminalState), ")")
		g.P("return outcome, nil")
	} else {
		g.P("info, err := capability.", methodName, "(", strings.Join(args, ", "), ")")
		g.P("if err != nil { return WithErrorContext(err, s.ProviderName(), ", fmt.Sprintf("%q", operation.ID), ") }")
		g.P("if err := s.replaceInfo(", fmt.Sprintf("%q", operation.ID), ", info); err != nil { return err }")
		if operation.TerminalState != "" {
			g.P("s.markTerminal(SandboxState", naming.Identifier(operation.TerminalState), ", ", fmt.Sprintf("%q", operation.TerminalState), ")")
		}
		g.P("return nil")
	}
	g.P("}")
	return nil
}

func findMessage(plugin *protogen.Plugin, name protoreflect.FullName) protogen.GoIdent {
	for _, file := range plugin.Files {
		for _, message := range file.Messages {
			if message.Desc.FullName() == name {
				return message.GoIdent
			}
		}
	}
	return protogen.GoIdent{}
}
